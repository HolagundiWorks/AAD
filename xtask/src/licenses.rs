//! `cargo xtask licenses`: the licence of every third-party Rust dependency.
//!
//! - Fails when a dependency has no declared licence, or one that is not on the allow list below
//!   (GPL, LGPL and AGPL are never allowed: AAD is MIT OR Apache-2.0 and links no copyleft code, see
//!   CLAUDE.md). An SPDX expression passes when at least one of its `OR` alternatives is allowed.
//! - Writes `THIRD_PARTY_LICENSES.md`, one row per package. With `--check` it writes nothing and
//!   fails instead when the file is out of date, so the file in the repository is always the real
//!   inventory of what is built.

use std::collections::BTreeMap;
use std::path::Path;

/// Licences accepted for dependencies (SPDX identifiers).
const ALLOWED: &[&str] = &[
    "MIT",
    "MIT-0",
    "Apache-2.0",
    "Apache-2.0 WITH LLVM-exception",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "ISC",
    "Zlib",
    "0BSD",
    "BSL-1.0",
    "CC0-1.0",
    "Unlicense",
    "Unicode-3.0",
    "Unicode-DFS-2016",
    "MPL-2.0",
    "OFL-1.1",
    "CDLA-Permissive-2.0",
    "OpenSSL",
    "NCSA",
];

/// Whether an SPDX expression is acceptable: some `OR` alternative whose `AND` parts are all allowed.
fn acceptable(expr: &str) -> bool {
    let cleaned = expr.replace(['(', ')'], " ").replace('/', " OR ");
    cleaned.split(" OR ").any(|alt| {
        let parts: Vec<&str> = alt.split(" AND ").map(str::trim).filter(|p| !p.is_empty()).collect();
        !parts.is_empty() && parts.iter().all(|p| ALLOWED.contains(p))
    })
}

struct Entry {
    name: String,
    version: String,
    license: String,
    repository: String,
}

fn collect(meta: &serde_json::Value) -> Vec<Entry> {
    let members: Vec<&str> = meta["workspace_members"].as_array().into_iter().flatten().filter_map(|v| v.as_str()).collect();
    let mut out = Vec::new();
    for p in meta["packages"].as_array().into_iter().flatten() {
        let id = p["id"].as_str().unwrap_or("");
        if members.contains(&id) || p["source"].is_null() {
            continue;
        }
        out.push(Entry {
            name: p["name"].as_str().unwrap_or("").to_string(),
            version: p["version"].as_str().unwrap_or("").to_string(),
            license: p["license"].as_str().unwrap_or("").trim().to_string(),
            repository: p["repository"].as_str().unwrap_or("").to_string(),
        });
    }
    out.sort_by(|a, b| (a.name.to_lowercase(), &a.version).cmp(&(b.name.to_lowercase(), &b.version)));
    out
}

fn render(entries: &[Entry]) -> String {
    let mut by_license: BTreeMap<&str, usize> = BTreeMap::new();
    for e in entries {
        *by_license.entry(e.license.as_str()).or_default() += 1;
    }
    let mut s = String::from("# Third-party licences\n\n");
    s.push_str("Generated by `cargo xtask licenses`: do not edit. Every dependency of the workspace, with the licence it declares.\n");
    s.push_str("AAD itself is MIT OR Apache-2.0 ([LICENSE-MIT](LICENSE-MIT), [LICENSE-APACHE](LICENSE-APACHE), [NOTICE](NOTICE)).\n");
    s.push_str("The check fails on any licence that is not on the allow list in `xtask/src/licenses.rs`; GPL, LGPL and AGPL are never allowed.\n\n");
    s.push_str(&format!("{} packages.\n\n## By licence\n\n| Licence | Packages |\n|---|---|\n", entries.len()));
    let mut counts: Vec<(&&str, &usize)> = by_license.iter().collect();
    counts.sort_by(|a, b| b.1.cmp(a.1).then(a.0.cmp(b.0)));
    for (l, n) in counts {
        s.push_str(&format!("| {l} | {n} |\n"));
    }
    s.push_str("\n## Packages\n\n| Package | Version | Licence | Source |\n|---|---|---|---|\n");
    for e in entries {
        s.push_str(&format!("| {} | {} | {} | {} |\n", e.name, e.version, e.license, e.repository));
    }
    s
}

pub fn run(root: &Path, check: bool) -> Result<(), String> {
    // Full metadata: the dependencies, not only the workspace members.
    let out = crate::cargo().args(["metadata", "--format-version", "1", "--locked"]).output().map_err(|e| format!("cargo metadata: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "cargo metadata failed:
{}",
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    let meta: serde_json::Value = serde_json::from_slice(&out.stdout).map_err(|e| format!("cargo metadata: bad JSON: {e}"))?;
    let entries = collect(&meta);
    let bad: Vec<String> = entries
        .iter()
        .filter(|e| e.license.is_empty() || !acceptable(&e.license))
        .map(|e| format!("{} {}: {}", e.name, e.version, if e.license.is_empty() { "no licence declared" } else { e.license.as_str() }))
        .collect();
    if !bad.is_empty() {
        return Err(format!("dependencies whose licence is not on the allow list ({}):\n  {}", bad.len(), bad.join("\n  ")));
    }
    let text = render(&entries);
    let path = root.join("THIRD_PARTY_LICENSES.md");
    if check {
        let have = std::fs::read_to_string(&path).unwrap_or_default().replace("\r\n", "\n");
        if have != text {
            return Err("THIRD_PARTY_LICENSES.md is out of date: run `cargo xtask licenses`".into());
        }
        println!("licenses: {} packages, all on the allow list; THIRD_PARTY_LICENSES.md is current", entries.len());
    } else {
        std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))?;
        println!("licenses: {} packages, all on the allow list; wrote THIRD_PARTY_LICENSES.md", entries.len());
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::acceptable;

    #[test]
    fn spdx_expressions_pass_when_one_alternative_is_allowed() {
        assert!(acceptable("MIT"));
        assert!(acceptable("MIT OR Apache-2.0"));
        assert!(acceptable("MIT/Apache-2.0"));
        assert!(acceptable("(MIT OR Apache-2.0) AND Unicode-3.0"));
        assert!(acceptable("Apache-2.0 WITH LLVM-exception OR GPL-3.0-only"), "an allowed alternative is enough");
        assert!(!acceptable("GPL-3.0-only"));
        assert!(!acceptable("LGPL-2.1-or-later OR AGPL-3.0-only"));
        assert!(!acceptable("MIT AND GPL-2.0-only"), "every AND part must be allowed");
        assert!(!acceptable(""));
    }
}
